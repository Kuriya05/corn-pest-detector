export const pestById = (id: string) => pests.find((p) => p.id === id);

/** จับคู่ชื่อที่ AI ตรวจพบ กับรายการในฐานข้อมูล */
export function matchPest(name: string): Pest | undefined {
  const q = name.toLowerCase().trim();
  if (!q) return undefined;
  return (
    pests.find((p) => p.nameTh === name || p.nameEn.toLowerCase() === q) ||
    pests.find((p) => p.matchKeywords.some((k) => q.includes(k.toLowerCase()) || k.toLowerCase().includes(q)))
  );
}
