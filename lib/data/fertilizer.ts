export function matchDeficiency(name: string): Deficiency | undefined {
  const q = name.toLowerCase().trim();
  if (!q) return undefined;
  return deficiencies.find((d) => d.matchKeywords.some((k) => q.includes(k.toLowerCase()) || k.toLowerCase().includes(q)));
}

/** คำนวณน้ำหนักปุ๋ยจากปริมาณธาตุอาหารที่ต้องการ */
export function kgFertilizer(nutrientKg: number, percent: number): number {
  if (percent <= 0) return 0;
  return (nutrientKg * 100) / percent;
}

/** แผนปุ๋ยจากค่าวิเคราะห์ดิน (ใช้ 18-46-0 + 46-0-0 + 0-0-60 ตามตารางกรมวิชาการเกษตร) */
export function buildSoilTestPlan(om: number, p: number, k: number, multiplier = 1) {
  const nTarget = (omLevels.find((l) => l.test(om)) ?? omLevels[1]).n * multiplier;
  const pTarget = (pLevels.find((l) => l.test(p)) ?? pLevels[1]).p;
  const kTarget = (kLevels.find((l) => l.test(k)) ?? kLevels[1]).k;

  // 18-46-0 ให้ฟอสฟอรัสทั้งหมด และแถมไนโตรเจนมาด้วย
  const dap = kgFertilizer(pTarget, 46);
  const nFromDap = (dap * 18) / 100;
  const mop = kgFertilizer(kTarget, 60);

  const nRemaining = Math.max(nTarget - nFromDap, 0);
  // แบ่งไนโตรเจนที่เหลือ: รองพื้นครึ่งหนึ่ง แต่งหน้าครึ่งหนึ่ง
  const ureaBase = kgFertilizer(nRemaining / 2, 46);
  const ureaTop = kgFertilizer(nRemaining / 2, 46);

  return {
    target: { n: nTarget, p: pTarget, k: kTarget },
    base: [
      { code: '18-46-0', kg: dap },
      { code: '46-0-0', kg: ureaBase },
      { code: '0-0-60', kg: mop },
    ].filter((x) => x.kg >= 0.5),
    topdress: [{ code: '46-0-0', kg: ureaTop }].filter((x) => x.kg >= 0.5),
    nFromDap,
  };
}

