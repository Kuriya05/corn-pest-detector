export const diseaseById = (id: string) => diseases.find((d) => d.id === id);

export function matchDisease(name: string): Disease | undefined {
  const q = name.toLowerCase().trim();
  if (!q) return undefined;
  return (
    diseases.find((d) => d.nameTh === name || d.nameEn.toLowerCase() === q) ||
    diseases.find((d) => d.matchKeywords.some((k) => q.includes(k.toLowerCase()) || k.toLowerCase().includes(q)))
  );
}
